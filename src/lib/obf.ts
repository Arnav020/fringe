"use client";

import JSZip from "jszip";
import type { Board } from "./types";
import { CORE, FITZGERALD } from "./vocab";

/**
 * Export to Open Board Format (.obz), the open interchange format for AAC
 * boards. The root board keeps core words in fixed positions and links to one
 * sub-board per fringe folder, so families can load the result into any
 * OBF-compatible AAC app instead of being locked into ours.
 */

const FORMAT = "open-board-0.1";

interface ObfButton {
  id: string;
  label: string;
  vocalization?: string;
  image_id?: string;
  background_color?: string;
  border_color?: string;
  load_board?: { id: string; path: string };
}

const hexToRgb = (hex: string) => {
  const n = parseInt(hex.slice(1), 16);
  return `rgb(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255})`;
};

function grid(ids: string[], columns: number) {
  const rows = Math.max(1, Math.ceil(ids.length / columns));
  const order: (string | null)[][] = [];
  for (let r = 0; r < rows; r++) {
    order.push(Array.from({ length: columns }, (_, c) => ids[r * columns + c] ?? null));
  }
  return { rows, columns, order };
}

/** The files of an Open Board Format package (.obz): one root board with fixed core words, one board per folder. */
export function obzFiles(board: Board): Record<string, unknown> {
  const files: Record<string, unknown> = {};
  const boardsPaths: Record<string, string> = {};
  const rootId = "root";

  const rootButtons: ObfButton[] = CORE.map((w, i) => ({
    id: `core-${i}`,
    label: w.word,
    vocalization: w.word,
    background_color: hexToRgb(FITZGERALD[w.cls].bg),
    border_color: "rgb(60, 60, 60)",
  }));

  for (const f of board.folders) {
    const fid = `folder-${f.key}${f.partner ? "-" + f.partner.replace(/\W+/g, "") : ""}`;
    const path = `boards/${fid}.obf`;
    boardsPaths[fid] = path;
    rootButtons.push({
      id: `link-${fid}`,
      label: f.title,
      background_color: f.key === "bridge" ? "rgb(245, 185, 207)" : "rgb(244, 185, 138)",
      border_color: "rgb(60, 60, 60)",
      load_board: { id: fid, path },
    });

    const images = f.cells
      .filter((c) => c.image)
      .map((c) => ({
        id: `img-${c.id}`,
        url: c.image!,
        content_type: "image/jpeg",
        width: 420,
        height: 420,
      }));
    const buttons: ObfButton[] = [
      ...f.cells.map((c) => ({
        id: c.id,
        label: c.label,
        vocalization: c.say,
        image_id: c.image ? `img-${c.id}` : undefined,
        background_color: "rgb(244, 185, 138)",
        border_color: "rgb(60, 60, 60)",
      })),
      ...f.quick.map((q, i) => ({
        id: `${fid}-q${i}`,
        label: q,
        vocalization: q,
        background_color: "rgb(245, 185, 207)",
        border_color: "rgb(60, 60, 60)",
      })),
      {
        id: `${fid}-home`,
        label: "Home",
        load_board: { id: rootId, path: "boards/root.obf" },
      },
    ];
    files[path] = {
      format: FORMAT,
      id: fid,
      locale: "en",
      name: `${board.person.name}: ${f.title}`,
      description_html: `Generated by Fringe from Qloo taste data.`,
      buttons,
      grid: grid(
        buttons.map((b) => b.id),
        5,
      ),
      images,
      sounds: [],
    };
  }

  boardsPaths[rootId] = "boards/root.obf";
  files["boards/root.obf"] = {
    format: FORMAT,
    id: rootId,
    locale: "en",
    name: `${board.person.name}'s board`,
    buttons: rootButtons,
    grid: grid(
      rootButtons.map((b) => b.id),
      8,
    ),
    images: [],
    sounds: [],
  };
  files["manifest.json"] = {
    format: FORMAT,
    root: "boards/root.obf",
    paths: { boards: boardsPaths },
  };
  return files;
}

export async function exportObz(board: Board) {
  const zip = new JSZip();
  for (const [path, json] of Object.entries(obzFiles(board))) zip.file(path, JSON.stringify(json, null, 2));
  const blob = await zip.generateAsync({ type: "blob" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = `${board.person.name.toLowerCase().replace(/\W+/g, "-")}-fringe.obz`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 2000);
}
